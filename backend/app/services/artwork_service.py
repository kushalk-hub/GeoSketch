logger = logging.getLogger(__name__)

#: File stems are generated by us, but validate anyway before touching the disk.
_SAFE_STEM = re.compile(r"^[A-Za-z0-9_-]{1,80}$")

ALLOWED_FORMATS = ("png", "svg")


def options_from_request(journey: Journey, request: ArtworkRequest) -> ArtworkOptions:
    customization = request.customization
    title = (
        (request.title or customization.title or journey.title or "Route artwork").strip()
        or "Route artwork"
    )
    return ArtworkOptions(
        title=title,
        subtitle=customization.subtitle,
        background=customization.background,
        route_color=customization.route_color,
        accent_color=customization.accent_color,
        line_width=customization.line_width,
        glow=customization.glow,
        show_start_marker=customization.show_start_marker,
        show_end_marker=customization.show_end_marker,
        palette=request.palette,
    )


def _load_route_points(db: Session, journey: Journey):
    points = ordered_points(db, journey.id)
    if not points:
        raise ValidationFailed(
            "this journey has no GPS points yet", code="no_route_points"
        )
    return points


def render_for_journey(
    db: Session, journey: Journey, request: ArtworkRequest, *, settings: Optional[Settings] = None
) -> Tuple[RenderResult, ArtworkOptions, int]:
    """Process the journey and render the requested style.

    Returns the render result, the options used, and the number of source points.
    """
    settings = settings or get_settings()
    points = _load_route_points(db, journey)
    options = options_from_request(journey, request)
    result = render_route_art(
        points,
        style=request.style,
        options=options,
        width=request.width,
        height=request.height,
        settings=settings,
        png_export=request.save,
    )
    return result, options, len(points)


def preview_artwork(
    db: Session, journey: Journey, request: ArtworkRequest, *, settings: Optional[Settings] = None
) -> ArtworkPreview:
    """Render an in-memory preview (SVG only, nothing written to disk)."""
    preview_request = request.model_copy(update={"save": False})
    result, _, source_points = render_for_journey(db, journey, preview_request, settings=settings)
    processed = result.processed
    processing = processed.processing_summary()
    processing["source_points"] = source_points
    return ArtworkPreview(
        style=result.style,
        title=result.title,
        width=result.width,
        height=result.height,
        svg=result.svg,
        point_count=processed.point_count,
        segment_count=processed.segment_count,
        distance_m=round(processed.distance_m, 3),
        duration_seconds=round(processed.duration_seconds, 3),
        processing=processing,
    )


def generate_artwork(
    db: Session, journey: Journey, request: ArtworkRequest, *, settings: Optional[Settings] = None
) -> Tuple[Artwork, RenderResult]:
    """Render and persist an artwork (PNG + SVG) for a journey."""
    settings = settings or get_settings()
    result, options, source_points = render_for_journey(
        db, journey, request, settings=settings
    )

    file_stem = f"journey{journey.id}-{result.style}-{uuid.uuid4().hex[:10]}"
    if not _SAFE_STEM.match(file_stem):  # pragma: no cover - defensive
        raise ValidationFailed("generated artwork name is invalid", code="invalid_filename")

    settings.artwork_dir.mkdir(parents=True, exist_ok=True)
    (settings.artwork_dir / f"{file_stem}.svg").write_text(result.svg, encoding="utf-8")
    png_bytes = result.png or render_route_art(
        ordered_points(db, journey.id),
        style=request.style,
        options=options,
        width=result.width,
        height=result.height,
        settings=settings,
        png_export=True,
    ).png
    (settings.artwork_dir / f"{file_stem}.png").write_bytes(png_bytes)

    customization = request.customization.model_dump(exclude_none=True)
    customization["palette"] = request.palette
    customization["subtitle"] = options.subtitle
    customization["title"] = options.title
    customization["width"] = result.width
    customization["height"] = result.height

    artwork = Artwork(
        journey_id=journey.id,
        title=options.title,
        style=result.style,
        customization=json.dumps(customization, sort_keys=True),
        export_format=request.export_format,
        file_stem=file_stem,
        width=result.width,
        height=result.height,
        point_count=result.processed.point_count,
        segment_count=result.processed.segment_count,
        distance_m=result.processed.distance_m,
    )
    db.add(artwork)
    db.commit()
    db.refresh(artwork)
    logger.info(
        "Rendered artwork %s (style=%s, %sx%s, points=%s) for journey %s",
        artwork.id,
        artwork.style,
        artwork.width,
        artwork.height,
        artwork.point_count,
        journey.id,
    )
    return artwork, result


def list_artworks(db: Session, journey_id: int) -> List[Artwork]:
    return list(
        db.scalars(
            select(Artwork)
            .where(Artwork.journey_id == journey_id)
            .order_by(Artwork.created_at.desc(), Artwork.id.desc())
        )
    )


def get_artwork(db: Session, artwork_id: int, *, journey: Optional[Journey] = None) -> Artwork:
    artwork = db.get(Artwork, artwork_id)
    if artwork is None or (journey is not None and artwork.journey_id != journey.id):
        raise NotFoundError(f"artwork {artwork_id} not found", code="artwork_not_found")
    return artwork


def artwork_file(artwork: Artwork, export_format: str, *, settings: Optional[Settings] = None) -> Path:
    """Resolve the file for an artwork, refusing anything outside the store."""
    settings = settings or get_settings()
    export_format = (export_format or artwork.export_format or "png").lower()
    if export_format not in ALLOWED_FORMATS:
        raise ValidationFailed(
            f"unsupported export format '{export_format}'",
            code="unsupported_format",
            details={"allowed": list(ALLOWED_FORMATS)},
        )
    if not _SAFE_STEM.match(artwork.file_stem or ""):
        raise ValidationFailed("artwork file name is invalid", code="invalid_filename")

    root = settings.artwork_dir.resolve()
    path = (root / f"{artwork.file_stem}.{export_format}").resolve()
    if root not in path.parents and path != root:
        raise ValidationFailed("artwork path escapes the artwork store", code="invalid_path")
    if not path.exists():
        raise NotFoundError(
            f"the {export_format} file for artwork {artwork.id} is not available",
            code="artwork_file_missing",
        )
    return path


def artwork_to_out(artwork: Artwork, *, settings: Optional[Settings] = None) -> ArtworkOut:
    settings = settings or get_settings()
    prefix = settings.api_v1_prefix
    model = ArtworkOut.model_validate(artwork)
    try:
        model.customization = json.loads(artwork.customization or "{}")
    except json.JSONDecodeError:  # pragma: no cover - defensive
        model.customization = {}
    model.png_url = f"{prefix}/artworks/{artwork.id}/download?format=png"
    model.svg_url = f"{prefix}/artworks/{artwork.id}/download?format=svg"
    return model


def delete_artwork_files(artworks: List[Artwork], *, settings: Optional[Settings] = None) -> int:
    """Remove the stored files for a set of artworks (used when deleting a journey)."""
    settings = settings or get_settings()
    removed = 0
    for artwork in artworks:
        for export_format in ALLOWED_FORMATS:
            try:
                path = artwork_file(artwork, export_format, settings=settings)
            except (NotFoundError, ValidationFailed):
                continue
            try:
                path.unlink()
                removed += 1
            except OSError:  # pragma: no cover - locked file
                logger.warning("Could not delete artwork file %s", path)
    return removed


def artwork_style_label(style: str) -> str:
    return style_label(style)
